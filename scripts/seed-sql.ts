/**
 * NOIRÉ — emit the seed as idempotent SQL.
 *
 *   npm run db:seed:sql            → writes supabase/seed.sql
 *   npm run db:seed:sql -- --stdout
 *
 * The output uses `jsonb_populate_recordset` so every column is cast by
 * Postgres itself (enums, numeric, text[], jsonb, timestamptz). Each statement
 * upserts on the table's natural key, so re-running is safe. Paste it into the
 * Supabase SQL Editor, or run `supabase db query -f supabase/seed.sql`.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { buildSeedBatches, type SeedBatch } from './seed-rows';

const TAG = '$noire_seed$';

function quoteIdent(name: string): string {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) throw new Error(`Unsafe identifier: ${name}`);
  return `"${name}"`;
}

export function batchToSql(batch: SeedBatch): string {
  if (batch.rows.length === 0) return `-- ${batch.table}: nothing to seed\n`;
  const columns = Array.from(new Set(batch.rows.flatMap((row) => Object.keys(row as object))));
  const keys = batch.conflict.split(',').map((k) => k.trim());
  const updatable = columns.filter((c) => !keys.includes(c));
  const json = JSON.stringify(batch.rows);
  if (json.includes(TAG)) throw new Error('Seed data collides with the dollar-quote tag.');
  const cols = columns.map(quoteIdent).join(', ');
  const update =
    updatable.length > 0
      ? `do update set ${updatable.map((c) => `${quoteIdent(c)} = excluded.${quoteIdent(c)}`).join(', ')}`
      : 'do nothing';
  return [
    `-- ${batch.table} (${batch.rows.length} rows)`,
    `insert into public.${quoteIdent(batch.table)} (${cols})`,
    `select ${cols}`,
    `from jsonb_populate_recordset(null::public.${quoteIdent(batch.table)}, ${TAG}${json}${TAG}::jsonb)`,
    `on conflict (${keys.map(quoteIdent).join(', ')}) ${update};`,
    '',
  ].join('\n');
}

export function buildSeedSql(): string {
  const header = [
    '-- NOIRÉ seed — generated by `npm run db:seed:sql`. Do not edit by hand.',
    '-- Idempotent: safe to re-run. Apply AFTER supabase/migrations/*.sql.',
    'begin;',
    '',
  ].join('\n');
  return header + buildSeedBatches().map(batchToSql).join('\n') + '\ncommit;\n';
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(__filename)) {
  const sql = buildSeedSql();
  if (process.argv.includes('--stdout')) {
    process.stdout.write(sql);
  } else {
    const out = resolve(__dirname, '../supabase/seed.sql');
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, sql, 'utf8');
    console.log(`✓ wrote ${out} (${(sql.length / 1024).toFixed(1)} kB)`);
  }
}
